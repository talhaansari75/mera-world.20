function puzzleDifficulty(puzzle) {
	const area = puzzle.size * puzzle.size;
	const density = puzzle.words.length / Math.max(1, area);
	const lengths = puzzle.words.map((w) => w.length);
	const avg = lengths.length ? lengths.reduce((a, b) => a + b, 0) / lengths.length : 0;
	const intersections = puzzle.placements.reduce((sum, p, i) => sum + puzzle.placements.slice(i + 1).filter((q) => p.cells.some((a) => q.cells.some((b) => a[0] === b[0] && a[1] === b[1]))).length, 0);
	const reverse = puzzle.placements.filter((p) => p.dr < 0 || p.dc < 0).length / Math.max(1, puzzle.placements.length);
	return Math.max(1, Math.min(100, Math.round(density * 140 + avg * 4 + intersections * 2 + reverse * 18)));
}
function validatePuzzleQuality(puzzle, requireUnique = true) {
	const errors = [];
	if (!puzzle.words.every((w) => typeof w === "string" && w.length >= 2)) errors.push("invalid_word");
	const occurrences = {};
	for (const word of puzzle.words) {
		const count = countWordOccurrences(puzzle, word);
		occurrences[word] = count;
		if (count < 1) errors.push(`unsolved:${word}`);
		if (requireUnique && count !== 1) errors.push(`non_unique:${word}:${count}`);
	}
	const density = puzzle.grid.flat().filter(Boolean).length / Math.max(1, puzzle.size * puzzle.size);
	const solvable = puzzle.words.every((w) => (occurrences[w] ?? 0) >= 1);
	const unique = puzzle.words.every((w) => (occurrences[w] ?? 0) === 1);
	return {
		valid: errors.length === 0,
		solvable,
		unique,
		density,
		difficulty: puzzleDifficulty(puzzle),
		occurrences,
		errors
	};
}
function canPlace(grid, word, row, col, dr, dc) {
	const n = grid.length;
	for (let i = 0; i < word.length; i++) {
		const r = row + dr * i;
		const c = col + dc * i;
		if (r < 0 || c < 0 || r >= n || c >= n) return false;
		const cell = grid[r][c];
		if (cell && cell !== word[i]) return false;
	}
	return true;
}
function placeWord(grid, word, row, col, dr, dc) {
	const cells = [];
	for (let i = 0; i < word.length; i++) {
		const r = row + dr * i;
		const c = col + dc * i;
		grid[r][c] = word[i];
		cells.push([r, c]);
	}
	return cells;
}
function tryPlace(grid, word, dirs, rng) {
	const n = grid.length;
	const coords = [];
	for (let r = 0; r < n; r++) for (let c = 0; c < n; c++) coords.push([r, c]);
	shuffle(rng, coords);
	const dorder = shuffle(rng, dirs.slice());
	for (const [dr, dc] of dorder) for (const [row, col] of coords) if (canPlace(grid, word, row, col, dr, dc)) return {
		word,
		row,
		col,
		dr,
		dc,
		cells: placeWord(grid, word, row, col, dr, dc)
	};
	return null;
}
